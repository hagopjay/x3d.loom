// tests/mapping.test.ts checks this table against the official X3DUOM field lists (src/bridge/uom-rigidbody-4.0.json).
//
// status:
//   mapped        PhysX does what X3D says
//   approximated  PhysX does something close; `how` says what differs
//   interpreted   X3D leaves room; the bridge declares its reading
//   output        the bridge writes this field from PhysX results
//   lost          no PhysX equivalent (or not built yet); ignored and reported
//   n/a           identity or presentation, not physics

export type Status = 'mapped' | 'approximated' | 'interpreted' | 'output' | 'lost' | 'n/a';
