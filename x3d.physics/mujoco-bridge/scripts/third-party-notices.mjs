// Generate THIRD_PARTY_NOTICES.txt from the packages actually inlined into dist/index.html.
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  exit 1 if the file is stale or a licence is not allowed
// Roots are the runtime imports of src/ (plus Tailwind, whose generated CSS is inlined); each root's
// production dependency tree is followed through node_modules. X_ITE is vendored beside the app with
// its own LICENSE.md and LICENSES/ (scripts/vendor-xite.mjs), so it is listed by reference.
import {readFileSync,writeFileSync,existsSync,readdirSync} from 'node:fs';
import path from 'node:path';

const ROOTS=['@mujoco/mujoco','react','react-dom','scheduler','three','clsx','tailwind-merge','jszip','tailwindcss'];
const ALLOWED=/^(\(?(MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|Zlib|0BSD)( (OR|AND) (MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|Zlib|0BSD|GPL-3\.0-or-later))*\)?)$/;
const ELECTED={jszip:'MIT (elected from "MIT OR GPL-3.0-or-later")'};

function pkgDir(name,from='.'){
 // Node resolution: nearest node_modules upward from `from`.
 let dir=path.resolve(from);
 for(;;){const d=path.join(dir,'node_modules',name);if(existsSync(path.join(d,'package.json')))return d;const up=path.dirname(dir);if(up===dir)return null;dir=up;}
}
const seen=new Map();
function walk(name,from){
 const dir=pkgDir(name,from);if(!dir)throw Error(`not installed: ${name}`);
 if(seen.has(dir))return;
 const pj=JSON.parse(readFileSync(path.join(dir,'package.json'),'utf8'));
 seen.set(dir,pj);
 for(const dep of Object.keys(pj.dependencies??{}))walk(dep,dir);
}
for(const r of ROOTS)walk(r,'.');

const licenceText=dir=>{
 const f=readdirSync(dir).find(n=>/^(licen[cs]e|copying)(\.(md|markdown|txt))?$/i.test(n));
 return f?readFileSync(path.join(dir,f),'utf8').trim():null;
};
const rows=[...seen].map(([dir,pj])=>({name:pj.name,version:pj.version,license:typeof pj.license==='string'?pj.license:JSON.stringify(pj.license??pj.licenses),text:licenceText(dir),repo:typeof pj.repository==='string'?pj.repository:pj.repository?.url,author:typeof pj.author==='string'?pj.author:pj.author?.name}))
 .sort((a,b)=>a.name.localeCompare(b.name));
const problems=rows.filter(r=>!ALLOWED.test(r.license)).map(r=>`${r.name}@${r.version}: licence "${r.license}" is not on the allow-list`);
// Packages without a licence file fall back to the standard text of their declared licence.
const MIT=readFileSync('node_modules/x_ite/LICENSES/MIT.txt','utf8').trim();
const APACHE=readFileSync('LICENSE','utf8').trim();

let out=`Third-party notices for the built application (dist/index.html)
Generated by scripts/third-party-notices.mjs from the installed packages; do not edit by hand.
The project itself is licensed under Apache-2.0 (LICENSE); see NOTICE.

X_ITE 16.7.0 (MIT) and its bundled assets are vendored beside the application in
dist/vendor/x_ite/ with their own LICENSE.md and LICENSES/ folder; see NOTICE.
`;
for(const r of rows){
 const lic=ELECTED[r.name]??r.license;
 let text=r.text;
 if(!text)text=`Copyright ${r.author??'the package authors'} (from package.json).\n\n`+(/Apache-2\.0/.test(r.license)?APACHE:/MIT/.test(r.license)?`${MIT}\n\n(Standard MIT text: the package declares MIT but ships no licence file.)`:'(no licence file in the package)');
 out+=`\n${r.name} ${r.version} — ${lic}\n${'='.repeat(70)}\n${r.repo?`Source: ${r.repo.replace(/^git\+/,'')}\n\n`:''}${text}\n`;
}

if(process.argv.includes('--check')){
 const cur=existsSync('THIRD_PARTY_NOTICES.txt')?readFileSync('THIRD_PARTY_NOTICES.txt','utf8'):'';
 if(cur!==out)problems.push('THIRD_PARTY_NOTICES.txt is stale: run node scripts/third-party-notices.mjs');
 if(problems.length){console.error(problems.join('\n'));process.exit(1);}
 console.log(`PASS third-party notices current: ${rows.length} packages, all on the licence allow-list`);
}else{
 if(problems.length){console.error(problems.join('\n'));process.exit(1);}
 writeFileSync('THIRD_PARTY_NOTICES.txt',out);console.log(`wrote THIRD_PARTY_NOTICES.txt: ${rows.length} packages`);
 for(const r of rows)console.log(`  ${r.name}@${r.version}  ${ELECTED[r.name]??r.license}${r.text?'':'  (no licence file; standard text used)'}`);
}
