#!/usr/bin/env python3
"""Tracker and loop driver of the three.js bridge (the counterpart of x3d.webgpu/bridge/tools/driver.py, kept small on purpose).

  driver.py init            build NODES.json from the Babylon tracker and the Babylon node files (never overwrites a three.js verdict that is already there)
  driver.py status          counts by three.js status and by component
  driver.py check NODE...   run tools/run-tests.js for the nodes (X_ITE 16.6.0 as the reference), write receipts/NODE.json, update NODES.json and NODES.md
  driver.py next [N]        the next N nodes that need the three.js body, by the Babylon rank (the order the Babylon bridge used: value first)

three.js status of a node:
  drawn      the three.js body draws it and a fixture passed against X_ITE (receipt)
  reader     event / logic node: lives in the shared reader, no engine call; "reader-checked" once a shared fixture passed through the three.js bundle
  todo       needs the three.js body (the Babylon spec has build / geometry / changed hooks, or the Babylon core body draws it) and has no passing fixture yet
  upstream   the Babylon bridge has not bridged it either (todo / gap / claimed / blocked there): nothing to port until it exists
"""
import json, os, re, subprocess, sys, datetime
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BAB = os.path.normpath(os.path.join(HERE, '..', '..', 'x3d.webgpu', 'bridge'))
TRK = os.path.join(HERE, 'NODES.json')
# nodes the Babylon core body (demo/src/brain/body.js) draws without a bridge node file
CORE_DRAW = {'Group', 'Switch', 'Transform', 'Shape', 'Appearance', 'Viewpoint', 'Box', 'Sphere', 'Cylinder', 'IndexedFaceSet', 'IndexedTriangleSet', 'IndexedLineSet', 'Text', 'Material', 'PhysicalMaterial',
             'ImageTexture', 'TextureTransform', 'TextureCoordinate', 'Coordinate', 'Color', 'Normal', 'Background', 'Fog', 'NavigationInfo', 'TouchSensor', 'ClipPlane', 'Billboard', 'EnvironmentLight', 'Sound',
             'LineProperties', 'ComposedShader', 'ShaderPart', 'PointLight', 'SpotLight', 'DirectionalLight', 'Cone', 'ElevationGrid', 'Extrusion', 'PointSet', 'Inline', 'LOD', 'Anchor', 'Collision', 'Rectangle2D', 'Disk2D'}
# what a three.js fixture exercises besides its own node (the fixture name is the node it is about)
COVERS = {'Box': ['Shape', 'Appearance', 'Material', 'NavigationInfo', 'Viewpoint'], 'IndexedFaceSet': ['Coordinate', 'Color'], 'DirectionalLight': ['NavigationInfo']}

def load(p): return json.load(open(p))
def hooks(name):
    f = os.path.join(BAB, 'src', 'nodes', name + '.js')
    return os.path.exists(f) and re.search(r'\b(build|geometry|changed)\s*[:(]', open(f).read()) is not None
def init():
    bab = load(os.path.join(BAB, 'NODES.json'))['nodes']; old = load(TRK)['nodes'] if os.path.exists(TRK) else {}
    out = {}
    for name, n in sorted(bab.items(), key=lambda kv: kv[1].get('rank', 999)):
        st = n['status']; cur = old.get(name, {}).get('three')
        if cur in ('drawn', 'reader-checked'): three = cur
        elif st in ('todo', 'gap', 'claimed', 'blocked') and not (name in CORE_DRAW or hooks(name)): three = 'upstream'
        elif name in CORE_DRAW or hooks(name): three = 'todo'
        else: three = 'reader'
        out[name] = {'component': n['component'], 'level': n.get('level'), 'rank': n.get('rank'), 'babylon': st, 'needs_body': name in CORE_DRAW or hooks(name), 'three': three,
                     **({'receipt': old[name]['receipt']} if name in old and 'receipt' in old[name] else {})}
    json.dump({'meta': {'tracker': 'three.js bridge', 'babylon_tracker': 'x3d.webgpu/bridge/NODES.json', 'total': len(out)}, 'nodes': out}, open(TRK, 'w'), indent=1); md()
def md():
    d = load(TRK)['nodes']; c = {}
    for n in d.values(): c[n['three']] = c.get(n['three'], 0) + 1
    L = ['# three.js bridge: node tracker (generated by tools/driver.py; edit NODES.json only through the driver)', '', 'Totals: ' + ', '.join(f'{k} {v}' for k, v in sorted(c.items())), '',
         '| node | component | Babylon | needs a body | three.js | receipt |', '|---|---|---|---|---|---|']
    for k, n in d.items(): L.append(f"| {k} | {n['component']} | {n['babylon']} | {'yes' if n['needs_body'] else 'no'} | {n['three']} | {n.get('receipt', '')} |")
    open(os.path.join(HERE, 'NODES.md'), 'w').write('\n'.join(L) + '\n')
def status():
    d = load(TRK)['nodes']; by = {}
    for n in d.values(): by.setdefault(n['component'], {}).setdefault(n['three'], 0); by[n['component']][n['three']] += 1
    tot = {}
    for n in d.values(): tot[n['three']] = tot.get(n['three'], 0) + 1
    print('total', len(d), tot)
    for k, v in sorted(by.items()): print(f'  {k:32s}', v)
def check(names):
    r = subprocess.run(['node', os.path.join(HERE, 'tools', 'run-tests.js'), *names], capture_output=True, text=True, env={**os.environ, 'NODE_PATH': os.environ.get('NODE_PATH', '/opt/node22/lib/node_modules')})
    line = [l for l in r.stdout.splitlines() if l.startswith('{')]
    if not line: print(r.stderr[-800:]); sys.exit(1)
    res = json.loads(line[-1]); d = load(TRK); today = datetime.date.today().isoformat()
    os.makedirs(os.path.join(HERE, 'receipts'), exist_ok=True)
    for n, v in res['results'].items():
        scene = str(v.get('mode', '')).startswith('scene')
        rec = {'node': n, 'date': today, 'env': res['env'], **v}
        json.dump(rec, open(os.path.join(HERE, 'receipts', n + '.json'), 'w'), indent=1)
        for t in [n] + (COVERS.get(n, []) if v['ok'] else []):
            if t in d['nodes'] and v['ok']: d['nodes'][t]['three'] = 'drawn' if scene else 'reader-checked'; d['nodes'][t]['receipt'] = f'receipts/{n}.json'
        print(('PASS ' if v['ok'] else 'FAIL ') + n + '  ours: ' + v['ours'][:90] + '  xite: ' + str(v['xite'])[:60])
    json.dump(d, open(TRK, 'w'), indent=1); md(); sys.exit(0 if res['ok'] else 1)
def nxt(k=10):
    d = load(TRK)['nodes']; todo = [(n['rank'] or 999, k2) for k2, n in d.items() if n['three'] == 'todo']
    for _, name in sorted(todo)[:k]: print(name, d[name]['component'], 'babylon:', d[name]['babylon'])
if __name__ == '__main__':
    a = sys.argv[1:] or ['status']
    {'init': init, 'status': status}.get(a[0], lambda: None)() if a[0] in ('init', 'status') else check(a[1:]) if a[0] == 'check' else nxt(int(a[1]) if len(a) > 1 else 10) if a[0] == 'next' else print(__doc__)
