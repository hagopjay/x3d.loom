"""Make demo/splat-test.x3d: a small procedural GaussianSplats scene (no third-party data). python3 -I src/gen-splat-test.py"""
import math, random, pathlib
random.seed(7)
P, S, Q, O, C = [], [], [], [], []
def add(p, s, q, o, c): P.append(p); S.append(s); Q.append(q); O.append(o); C.append(c)
def quat(axis, ang):
    n = math.sqrt(sum(x * x for x in axis)); s = math.sin(ang / 2) / n
    return (axis[0] * s, axis[1] * s, axis[2] * s, math.cos(ang / 2))
# a ground disc, a ring of pillars, a central sphere: ~6,000 splats
for _ in range(2200):
    r = 6 * math.sqrt(random.random()); t = random.random() * 6.2832
    add((r * math.cos(t), 0.0, r * math.sin(t)), (0.13, 0.13, 0.012), quat((1, 0, 0), 1.5708), 0.7, [(r / 6) * 1.0, 0.6 - r / 14, 0.9 - r / 8])
for k in range(8):
    a = k * 6.2832 / 8
    for _ in range(300):
        y = random.random() * 2.4; t = random.random() * 6.2832
        add((4 * math.cos(a) + 0.18 * math.cos(t), y, 4 * math.sin(a) + 0.18 * math.sin(t)), (0.05, 0.12, 0.05), quat((0, 1, 0), t), 0.8, [0.9, 0.55 + y / 6, 0.25])
for _ in range(1500):
    u = random.random() * 2 - 1; t = random.random() * 6.2832; r = math.sqrt(1 - u * u)
    add((1.1 * r * math.cos(t), 1.4 + 1.1 * u, 1.1 * r * math.sin(t)), (0.07, 0.07, 0.07), (0, 0, 0, 1), 0.85, [0.3 + 0.4 * (u + 1) / 2, 0.55, 1.0])
SH = 0.28209479177387814
f = lambda xs: ' '.join(f'{x:.5f}' for x in xs)
pos = f([c for p in P for c in p]); sc = f([c for p in S for c in p]); qs = f([c for p in Q for c in p])
op = f(O); sh = f([(max(0.0, min(1.0, c)) - 0.5) / SH for col in C for c in col])
x = f'''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE X3D PUBLIC "ISO//Web3D//DTD X3D 4.1//EN" "https://www.web3d.org/specifications/x3d-4.1.dtd">
<X3D version="4.1" profile="Immersive" xmlns:xsd="http://www.w3.org/2001/XMLSchema-instance" xsd:noNamespaceSchemaLocation="https://www.web3d.org/specifications/x3d-4.1.xsd">
  <head>
    <component name="GaussianSplats" level="1" />
    <meta name="title" content="Splat test: a pavilion of {len(P):,} procedural splats" />
    <meta name="description" content="A small procedural GaussianSplats scene for checking splat renderers: ground disc, eight pillars, a sphere. Orientations are x y z w; scales are linear; opacities 0..1; colour is the degree-0 spherical-harmonic coefficient." />
    <meta name="license" content="CC0 (generated by src/gen-splat-test.py)" />
  </head>
  <Scene>
    <NavigationInfo headlight="false" type='"EXAMINE" "ANY"' />
    <Viewpoint DEF="Hall" description="Hall" position="0 1.6 9" orientation="1 0 0 -0.08" fieldOfView="0.9" centerOfRotation="0 1.2 0" />
    <Viewpoint DEF="Inside" description="Inside" position="0 1.5 0" orientation="0 1 0 0.7" fieldOfView="1.2" />
    <GaussianSplats DEF="Pavilion" positions="{pos}" scales="{sc}" orientations="{qs}" opacities="{op}" sphericalHarmonicsDegree0Coef0="{sh}" />
  </Scene>
</X3D>
'''
out = pathlib.Path(__file__).resolve().parent.parent / 'splat-test.x3d'
out.write_text(x); print(out, len(x), len(P))
