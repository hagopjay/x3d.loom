"""Lift the X3D Metadata that Blender's glTF exporter writes as plain `extras` into KHR_xmp_json_ld packets.

    python -I semantic/blender_extras.py lift IN.glb|IN.gltf OUT.glb|OUT.gltf [SOURCE.x3d]     prints the report as JSON

Why: the x3d-blender-io add-on (2.6.5 and later) keeps every imported Metadata tree in custom properties, and Blender's
glTF exporter (custom properties on) writes them out as `extras`:

    node.extras.x3d_metadata              the Shape's tree
    node.extras.x3d_transform_metadata    the tree of the Transform the object stands for
    material.extras.x3d_metadata          the tree of the Material / PhysicalMaterial / UnlitMaterial
    scene.extras.x3d_scene_metadata       a list for every other host (WorldInfo, sensors, ...)

That is all the data, but it is untyped: values are X3D field TEXT ("9.62", '"a" "b"'), nothing says which vocabulary a
key belongs to, and no JSON-LD tool can query it. The lift turns each tree into the same packet shape x3dsem writes
(X3D-exact core, typed values, crm:/ifc: @type lifts) and attaches it where the extras were:
node -> node packet, material -> MATERIAL packet, scene -> SCENE packet (KHR_xmp_json_ld allows all three, so the two
hosts x3dsem 0.1.0 cannot carry, materials and WorldInfo, arrive here).

The lift is additive: extras are left as they are, geometry and the binary chunk are untouched byte for byte.

Rules (each has a mutation test in test_blender_extras.py):
  L0  packet structure (same check as x3dsem S0)
  L1  every Metadata tree of the SOURCE X3D is a packet on the same kind of host with the same DEF, value for value
  L2  Metadata node count equals the source's (none dropped, none invented)
  L3  every CIDOC-CRM class reference of the source is typed in JSON-LD (@type crm:E..)
  L4  every number in a MetadataDouble/Float/Integer packet is a JSON number, every boolean a JSON boolean
  L5  additive: the output without the extension equals the input (extras, nodes, meshes, buffers unchanged)
  L6  the asset packet carries PROV-O (derived from the sha256 of the input glTF, generated by this lifter)
L1-L3 need SOURCE.x3d; without it they are reported as "not run", never as pass.

Known limits, stated so nobody has to find them: the extras do not say which material node type the host was, so L1
compares hosts by KIND (node:Transform, node:Shape, material, or the X3D type for scene-level hosts); the add-on does
not keep metadata-on-metadata, so such a child fails L1/L2 rather than passing quietly. Stdlib only.
"""
from __future__ import annotations

import copy
import hashlib
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import x3dsem  # noqa: E402

LIFTER = "loom-gltf blender_extras 0.1.0"
EXT = "KHR_xmp_json_ld"
MATERIAL_TYPES = {"Material", "PhysicalMaterial", "UnlitMaterial", "TwoSidedMaterial"}
NUMERIC = {"x3d:MetadataDouble", "x3d:MetadataFloat", "x3d:MetadataInteger"}


# ------------------------------------------------------------------------------------------------------ glTF / glb io
def load(path: Path) -> tuple[dict, bytes | None]:
    raw = path.read_bytes()
    if raw[:4] != b"glTF":
        return json.loads(raw), None
    n = struct.unpack_from("<I", raw, 12)[0]
    g = json.loads(raw[20:20 + n])
    rest = raw[20 + n:]
    return g, rest  # rest = the BIN chunk (header + data) exactly as it was, or b""


def save(path: Path, g: dict, rest: bytes | None) -> None:
    if rest is None:
        path.write_text(json.dumps(g, indent=1))
        return
    js = json.dumps(g, separators=(",", ":"), ensure_ascii=False).encode()
    js += b" " * (-len(js) % 4)
    path.write_bytes(struct.pack("<4sII", b"glTF", 2, 12 + 8 + len(js) + len(rest)) + struct.pack("<I4s", len(js), b"JSON") + js + rest)


# ------------------------------------------------------------------------------------------------------ add-on tree -> x3dsem tree
def tree(d: dict) -> dict:
    """The add-on's nested dict (node, def, name, reference, value as X3D text) as x3dsem's typed tree."""
    t = d["node"]
    if t not in x3dsem.META_TYPES:
        raise ValueError(f"not a Metadata node: {t!r}")
    out: dict = {"type": t}
    for src, dst in (("name", "name"), ("reference", "reference"), ("def", "DEF")):
        if d.get(src) not in (None, ""):
            out[dst] = d[src]
    v = d.get("value")
    if t == "MetadataSet":
        out["value"] = [tree(c) for c in (v or [])]
    elif t == "MetadataString":
        out["value"] = x3dsem.parse_mfstring(v)
    elif t in ("MetadataDouble", "MetadataFloat"):
        out["value"] = x3dsem.floats(v)
    elif t == "MetadataInteger":
        out["value"] = x3dsem.ints(v)
    else:
        out["value"] = x3dsem.bools(v)
    if isinstance(d.get("metadata"), dict):
        out["metadata"] = tree(d["metadata"])
    return out


def kind(host_type: str) -> str:
    if host_type in MATERIAL_TYPES:
        return "material"
    if host_type in ("Transform", "Shape"):
        return "node:" + host_type
    return host_type


def found(g: dict) -> list[dict]:
    """Every Metadata tree in the extras: where it is, what host it speaks for, the typed tree. Bad trees are reported."""
    out = []

    def add(coll, i, key, host, DEF, raw, extra=None):
        e = {"collection": coll, "index": i, "key": key, "hostKind": host, "DEF": DEF or None}
        try:
            e["metadata"] = tree(raw)
        except (KeyError, TypeError, ValueError) as exc:
            e["error"] = f"{type(exc).__name__}: {exc}"
        if extra:
            e["extra"] = extra
        out.append(e)

    for i, n in enumerate(g.get("nodes", [])):
        x = n.get("extras") or {}
        if isinstance(x.get("x3d_transform_metadata"), dict):
            path = x.get("x3d_def_path") or ""
            add("nodes", i, "x3d_transform_metadata", "node:Transform", path.rsplit("/", 1)[-1] or x.get("x3d_def"), x["x3d_transform_metadata"])
        if isinstance(x.get("x3d_metadata"), dict):
            add("nodes", i, "x3d_metadata", "node:Shape", x.get("x3d_shape_def") or None, x["x3d_metadata"])
    for i, m in enumerate(g.get("materials", [])):
        x = m.get("extras") or {}
        if isinstance(x.get("x3d_metadata"), dict):
            add("materials", i, "x3d_metadata", "material", x.get("x3d_def") or m.get("name"), x["x3d_metadata"])
    for i, s in enumerate(g.get("scenes", [])):
        for entry in (s.get("extras") or {}).get("x3d_scene_metadata") or []:
            if isinstance(entry, dict) and isinstance(entry.get("metadata"), dict):
                add("scenes", i, "x3d_scene_metadata", kind(entry.get("host") or "?"), entry.get("def"), entry["metadata"],
                    {k: entry[k] for k in ("host", "path", "title", "info") if entry.get(k) not in (None, "")})
    return out


# ------------------------------------------------------------------------------------------------------ the lift
def lift(g: dict, input_sha256: str, input_name: str = "") -> tuple[dict, dict]:
    """Returns (new glTF JSON, report). `g` is not modified."""
    out = copy.deepcopy(g)
    items = found(out)
    packets = out.setdefault("extensions", {}).setdefault(EXT, {}).setdefault("packets", [])
    if EXT not in out.setdefault("extensionsUsed", []):
        out["extensionsUsed"].append(EXT)

    def packet(obj) -> int:
        packets.append({"@context": x3dsem.CONTEXT, **obj})
        return len(packets) - 1

    def attach(target: dict, pk: dict, where: str) -> int:
        ext = target.setdefault("extensions", {})
        if EXT in ext:  # the host already has a packet (two trees on one glTF object): add a graph entry, do not overwrite
            cur = packets[ext[EXT]["packet"]]
            cur.setdefault("loom:alsoHosts", []).append(pk)
            return ext[EXT]["packet"]
        i = packet({"@id": where, **pk})
        ext[EXT] = {"packet": i}
        return i

    asset_i = None
    if "extensions" not in out["asset"] or EXT not in out["asset"]["extensions"]:
        asset_i = packet({"@id": "loom:asset", "dc:format": "model/gltf-binary",
                          "prov:wasDerivedFrom": {"@id": "urn:sha256:" + input_sha256, "dc:title": input_name,
                                                  "loom:generator": g.get("asset", {}).get("generator")},
                          "prov:wasGeneratedBy": {"@type": "prov:Activity", "prov:used": LIFTER}})
        out["asset"].setdefault("extensions", {})[EXT] = {"packet": asset_i}
    lifted, errors = [], []
    for it in items:
        if "error" in it:
            errors.append({k: it[k] for k in ("collection", "index", "key", "error")})
            continue
        pk = {"x3d:hostKind": it["hostKind"], "loom:fromExtras": it["key"], "x3d:metadata": x3dsem.lift(it["metadata"])}
        if it["DEF"]:
            pk["x3d:hostDEF"] = it["DEF"]
        if it.get("extra"):
            pk["loom:host"] = it["extra"]
        i = attach(out[it["collection"]][it["index"]], pk, f"loom:{it['collection']}/{it['index']}")
        lifted.append({"collection": it["collection"], "index": it["index"], "key": it["key"], "hostKind": it["hostKind"], "DEF": it["DEF"],
                       "packet": i, "metadata_nodes": sum(1 for _ in x3dsem.walk_meta(it["metadata"]))})
    report = {"schema": "loom.extras-lift/1", "lifter": LIFTER, "input": {"file": input_name, "sha256": input_sha256, "generator": g.get("asset", {}).get("generator")},
              "trees_found": len(items), "trees_lifted": len(lifted), "metadata_nodes": sum(x["metadata_nodes"] for x in lifted),
              "packets": len(packets), "lifted": lifted, "errors": errors}
    return out, report


def hosts_in(g: dict) -> list[dict]:
    """What a consumer reads back from the packets alone (never from extras)."""
    packets = g.get("extensions", {}).get(EXT, {}).get("packets", [])
    out = []
    for coll in ("scenes", "nodes", "materials"):
        for o in g.get(coll, []):
            ref = o.get("extensions", {}).get(EXT, {}).get("packet")
            if not isinstance(ref, int) or not 0 <= ref < len(packets):
                continue
            p = packets[ref]
            for q in [p] + list(p.get("loom:alsoHosts", [])):
                if "x3d:metadata" in q:
                    out.append({"hostKind": q.get("x3d:hostKind"), "DEF": q.get("x3d:hostDEF"), "metadata": x3dsem.unlift(q["x3d:metadata"])})
    return out


def _strip(g: dict) -> dict:
    s = copy.deepcopy(g)
    s.get("extensions", {}).pop(EXT, None)
    if not s.get("extensions"):
        s.pop("extensions", None)
    if EXT in s.get("extensionsUsed", []):
        s["extensionsUsed"].remove(EXT)
    if not s.get("extensionsUsed"):
        s.pop("extensionsUsed", None)
    for o in [s.get("asset", {})] + [o for c in ("scenes", "nodes", "materials") for o in s.get(c, [])]:
        o.get("extensions", {}).pop(EXT, None)
        if "extensions" in o and not o["extensions"]:
            del o["extensions"]
    return s


def _typed(node, bad):
    if isinstance(node, dict):
        t = node.get("@type")
        t0 = (t[0] if isinstance(t, list) else t) or ""
        vals = node.get("x3d:value", {}).get("@list", []) if isinstance(node.get("x3d:value"), dict) else []
        if t0 in NUMERIC and any(isinstance(v, bool) or not isinstance(v, (int, float)) for v in vals):
            bad.append(node.get("x3d:name"))
        if t0 == "x3d:MetadataBoolean" and any(not isinstance(v, bool) for v in vals):
            bad.append(node.get("x3d:name"))
        for v in node.values():
            _typed(v, bad)
    elif isinstance(node, list):
        for v in node:
            _typed(v, bad)


def rules(before: dict, after: dict, source: dict | None) -> list[dict]:
    """L0..L6. `source` is x3dsem.semantics(SOURCE.x3d) or None."""
    out = []
    packets = after.get("extensions", {}).get(EXT, {}).get("packets", [])
    refs = [o["extensions"][EXT]["packet"] for coll in ("nodes", "meshes", "materials", "scenes") for o in after.get(coll, [])
            if EXT in o.get("extensions", {})] + ([after["asset"]["extensions"][EXT]["packet"]] if EXT in after.get("asset", {}).get("extensions", {}) else [])
    bad = [r for r in refs if not (isinstance(r, int) and 0 <= r < len(packets))] + [i for i, p in enumerate(packets) if "@context" not in p]
    out.append({"id": "L0", "rule": "KHR_xmp_json_ld structure: declared in extensionsUsed, every packet has @context, every reference is in range",
                "packets": len(packets), "references": len(refs), "bad": len(bad), "pass": EXT in after.get("extensionsUsed", []) and not bad})
    got = hosts_in(after) if not bad else []
    B = sorted(x3dsem.canon((h["hostKind"], h["DEF"], h["metadata"])) for h in got)
    nodes_b = sum(1 for h in got for _ in x3dsem.walk_meta(h["metadata"]))
    lifted = x3dsem.canon(packets)
    if source is None:
        for i, text in (("L1", "every source Metadata tree is a packet on the same kind of host with the same DEF, value for value"),
                        ("L2", "Metadata node count equals the source's"), ("L3", "every CIDOC-CRM class reference of the source is typed in JSON-LD")):
            out.append({"id": i, "rule": text, "pass": None, "note": "not run: no source X3D given"})
    else:
        A = sorted(x3dsem.canon((kind(h["hostType"]), h["DEF"], h["metadata"])) for h in source["hosts"])
        out.append({"id": "L1", "rule": "every Metadata tree of the source X3D is a packet on the same kind of host with the same DEF, value for value",
                    "expected": len(A), "got": len(B), "missing": len([x for x in A if x not in B]), "extra": len([x for x in B if x not in A]), "pass": A == B})
        nodes_a = sum(1 for h in source["hosts"] for _ in x3dsem.walk_meta(h["metadata"]))
        out.append({"id": "L2", "rule": "Metadata node count equals the source's (none dropped, none invented)", "expected": nodes_a, "got": nodes_b, "pass": nodes_a == nodes_b})
        crm = sorted(d["reference"] for h in source["hosts"] for d, _ in x3dsem.walk_meta(h["metadata"]) if "cidoc-crm" in (d.get("reference") or ""))
        typed = sum(lifted.count('"crm:' + r.rsplit("/", 1)[-1] + '"') > 0 for r in crm)
        out.append({"id": "L3", "rule": "every CIDOC-CRM class reference of the source is typed in JSON-LD (@type crm:E..)", "expected": len(crm), "typed_in_gltf": typed, "pass": typed == len(crm)})
    untyped: list = []
    _typed(packets, untyped)
    out.append({"id": "L4", "rule": "every number in a numeric Metadata packet is a JSON number and every boolean a JSON boolean (extras carry them as text)",
                "untyped": len(untyped), "pass": not untyped})
    out.append({"id": "L5", "rule": "additive: the output without the extension equals the input (extras, nodes, meshes, buffers unchanged)",
                "pass": x3dsem.canon(_strip(after)) == x3dsem.canon(_strip(before))})
    ai = after.get("asset", {}).get("extensions", {}).get(EXT, {}).get("packet")
    asset = packets[ai] if isinstance(ai, int) and 0 <= ai < len(packets) else {}
    out.append({"id": "L6", "rule": "asset packet carries PROV-O: prov:wasDerivedFrom = sha256 of the input glTF, prov:wasGeneratedBy = the lifter",
                "pass": bool(str(asset.get("prov:wasDerivedFrom", {}).get("@id", "")).startswith("urn:sha256:")) and bool(asset.get("prov:wasGeneratedBy"))})
    return out


def run(src: Path, dst: Path, source_x3d: Path | None = None) -> dict:
    g, rest = load(src)
    sha = hashlib.sha256(src.read_bytes()).hexdigest()
    out, report = lift(g, sha, src.name)
    save(dst, out, rest)
    back, rest2 = load(dst)
    rs = rules(g, back, x3dsem.semantics(source_x3d) if source_x3d else None)
    report["output"] = {"file": dst.name, "sha256": hashlib.sha256(dst.read_bytes()).hexdigest(), "bin_chunk_unchanged": rest == rest2}
    if source_x3d:
        report["source"] = {"file": source_x3d.name, "sha256": hashlib.sha256(source_x3d.read_bytes()).hexdigest()}
    report["rules"] = rs
    report["verdict"] = "fail" if any(r["pass"] is False for r in rs) or report["errors"] or rest != rest2 else ("pass" if all(r["pass"] for r in rs) else "pass (source rules not run)")
    return report


if __name__ == "__main__":
    if len(sys.argv) not in (4, 5) or sys.argv[1] != "lift":
        print(__doc__)
        sys.exit(2)
    r = run(Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4]) if len(sys.argv) == 5 else None)
    print(json.dumps(r, indent=1))
    sys.exit(1 if r["verdict"] == "fail" else 0)
